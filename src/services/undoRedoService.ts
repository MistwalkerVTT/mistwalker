import { Token, WallSegment } from '../types';

export type UndoActionType =
  | 'TOKEN_MOVE'
  | 'TOKEN_ADD'
  | 'TOKEN_DELETE'
  | 'TOKEN_HP'
  | 'WALLS_CHANGE'
  | 'FOG_CHANGE';

export interface TokenMovePayload {
  tokenId: string;
  tokenName: string;
  from: { x: number; y: number };
  to: { x: number; y: number };
}

export interface TokenHpPayload {
  tokenId: string;
  tokenName: string;
  oldHp: { currentHp: number; maxHp: number; tempHp?: number };
  newHp: { currentHp: number; maxHp: number; tempHp?: number };
}

export interface WallsChangePayload {
  description: string;
  oldWalls: WallSegment[];
  newWalls: WallSegment[];
}

export interface UndoAction {
  id: string;
  type: UndoActionType;
  description: string;
  timestamp: number;
  payload: any;
}

class UndoRedoService {
  private undoStack: UndoAction[] = [];
  private redoStack: UndoAction[] = [];
  private maxDepth = 50;
  private listeners: Set<() => void> = new Set();
  private isApplying = false;

  public subscribe(listener: () => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  private notify() {
    this.listeners.forEach(cb => {
      try { cb(); } catch (e) { console.error(e); }
    });
  }

  public get isApplyingAction(): boolean {
    return this.isApplying;
  }

  public setApplying(val: boolean) {
    this.isApplying = val;
  }

  public recordAction(action: Omit<UndoAction, 'id' | 'timestamp'>) {
    if (this.isApplying) return; // Do not record actions generated by an undo/redo execution

    const fullAction: UndoAction = {
      ...action,
      id: `undo-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      timestamp: Date.now()
    };

    this.undoStack.push(fullAction);
    if (this.undoStack.length > this.maxDepth) {
      this.undoStack.shift();
    }
    // Any new action clears the redo stack
    this.redoStack = [];
    this.notify();
  }

  public undo(): UndoAction | null {
    if (this.undoStack.length === 0) return null;
    const action = this.undoStack.pop()!;
    this.redoStack.push(action);
    this.notify();
    return action;
  }

  public redo(): UndoAction | null {
    if (this.redoStack.length === 0) return null;
    const action = this.redoStack.pop()!;
    this.undoStack.push(action);
    this.notify();
    return action;
  }

  public canUndo(): boolean {
    return this.undoStack.length > 0;
  }

  public canRedo(): boolean {
    return this.redoStack.length > 0;
  }

  public getUndoDescription(): string {
    const last = this.undoStack[this.undoStack.length - 1];
    return last ? `Undo: ${last.description}` : 'Nothing to undo';
  }

  public getRedoDescription(): string {
    const last = this.redoStack[this.redoStack.length - 1];
    return last ? `Redo: ${last.description}` : 'Nothing to redo';
  }

  public clear() {
    this.undoStack = [];
    this.redoStack = [];
    this.notify();
  }
}

export const undoRedo = new UndoRedoService();
