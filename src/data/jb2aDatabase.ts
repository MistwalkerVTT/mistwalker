/**
 * Find JB2A asset definition by exact ID or fuzzy spell name/tag matching
 */
export function findJb2aAsset(query: string): Jb2aAsset | undefined {
  if (!query) return undefined;
  const q = query.toLowerCase().trim().replace(/_/g, ' ');

  // 1. Direct match on ID
  const direct = JB2A_DATABASE.find(a => a.id.toLowerCase() === q || a.id.replace(/_/g, ' ') === q);
  if (direct) return direct;

  // 2. Exact match on name/label
  const nameMatch = JB2A_DATABASE.find(a => a.name.toLowerCase() === q || a.label.toLowerCase() === q);
  if (nameMatch) return nameMatch;

  // 3. Substring match on name
  const subMatch = JB2A_DATABASE.find(a => a.name.toLowerCase().includes(q) || q.includes(a.name.toLowerCase()));
  if (subMatch) return subMatch;

  // 4. Tag match
  return JB2A_DATABASE.find(a => a.tags.some(t => t.includes(q) || q.includes(t)));
}

/**
 * Get JB2A asset by exact ID
 */
export function getJb2aAsset(id: string): Jb2aAsset | undefined {
  return JB2A_DATABASE.find(a => a.id === id);
}
