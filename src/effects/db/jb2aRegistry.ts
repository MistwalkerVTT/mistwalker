export function getJb2aAssetById(id: string): Jb2aAssetDefinition | undefined {
  if (!id) return undefined;
  const target = id.toLowerCase().trim().replace(/[\s-]+/g, '_');
  return JB2A_REGISTRY.find(a => a.id === target || a.name.toLowerCase() === target);
}

export function findJb2aAsset(query: string): Jb2aAssetDefinition | undefined {
  if (!query) return undefined;
  const q = query.toLowerCase().trim().replace(/[\s-]+/g, '_');
  const rawQ = query.toLowerCase().trim();

  // 1. Direct ID or Name match
  const direct = JB2A_REGISTRY.find(a => a.id === q || a.name.toLowerCase() === rawQ);
  if (direct) return direct;

  // 2. Tag match
  const tagMatch = JB2A_REGISTRY.find(a => a.tags.some(t => t === rawQ || t === q));
  if (tagMatch) return tagMatch;

  // 3. Substring match
  return JB2A_REGISTRY.find(a => a.name.toLowerCase().includes(rawQ) || rawQ.includes(a.name.toLowerCase()));
}
